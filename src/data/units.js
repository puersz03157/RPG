const DARK_SLIME_BASE = MONSTERS_BASE.find((m) => m.id === 'm4') ?? MONSTERS_BASE[0];
const LIGHT_SLIME_BASE = MONSTERS_BASE.find((m) => m.id === 'm5') ?? MONSTERS_BASE[0];

function scaleMonsterLinear(monsterBase, mul, overrides = {}) {
  const m = monsterBase ?? {};
  const k = Math.max(0.1, Number(mul) || 1);
  return {
    ...m,
    hp: Math.max(1, Math.round((m.hp ?? 1) * k)),
    atk: Math.max(1, Math.round((m.atk ?? 1) * k)),
    def: Math.max(1, Math.round((m.def ?? 1) * k)),
    spd: Math.max(1, Math.round((m.spd ?? 1) * k)),
    ...(m.matk != null ? { matk: Math.max(0, Math.round(m.matk * k)) } : null),
    ...(m.mdef != null ? { mdef: Math.max(0, Math.round(m.mdef * k)) } : null),
    ...overrides,
  };
}

function buildExpStage(tier, levelRangeText, mul, perMonsterXp) {
  const t = Math.max(1, Math.min(5, Math.floor(Number(tier) || 1)));
  const monsters = Array.from({ length: 5 }).map(() =>
    scaleMonsterLinear(DARK_SLIME_BASE, mul, {
      name: `暗史萊姆（經驗）`,
      xpReward: Math.max(1, Math.floor(perMonsterXp)),
      goldReward: 0,
    })
  );
  return {
    id: `xp-${t}`,
    kind: 'xp',
    title: `經驗關卡 ${t}`,
    subtitle: `${levelRangeText} · 每日可刷 3 次`,
    monsters,
  };
}

function buildGoldStage(tier, levelRangeText, mul, perMonsterGold, perMonsterXp) {
  const t = Math.max(1, Math.min(5, Math.floor(Number(tier) || 1)));
  const monsters = Array.from({ length: 5 }).map(() =>
    scaleMonsterLinear(LIGHT_SLIME_BASE, mul, {
      name: `光史萊姆（金錢）`,
      // 金錢關卡：不提供經驗值（經驗請去經驗關卡刷）
      xpReward: 0,
      goldReward: Math.max(1, Math.floor(perMonsterGold)),
    })
  );
  return {
    id: `gl-${t}`,
    kind: 'gold',
    title: `金錢關卡 ${t}`,
    subtitle: `${levelRangeText} · 每日可刷 3 次`,
    monsters,
  };
}

